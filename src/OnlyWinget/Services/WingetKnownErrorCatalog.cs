    public static bool TryGetSymbol(int exitCode, out string symbol) => Symbols.TryGetValue(exitCode, out symbol!);

    public static bool TryGetLabel(int exitCode, out string label)
    {
        if (!TryGetSymbol(exitCode, out var symbol))
        {
            label = string.Empty;
            return false;
        }

        label = FormatSymbolLabel(symbol);
        return true;
    }

    public static string FormatHex(int exitCode) => $"0x{unchecked((uint)exitCode):X8}";

    private static string FormatSymbolLabel(string symbol)
    {
        var cleaned = symbol
            .Replace("APPINSTALLER_CLI_ERROR_", string.Empty, StringComparison.Ordinal)
            .Replace("WINGET_INSTALLED_STATUS_", string.Empty, StringComparison.Ordinal)
            .Replace("WINGET_CONFIG_ERROR_", string.Empty, StringComparison.Ordinal);
        var textInfo = CultureInfo.InvariantCulture.TextInfo;
        return textInfo.ToTitleCase(cleaned.Replace('_', ' ').ToLowerInvariant());
    }

    public static int Count => Symbols.Count;

    public static bool ContainsDuplicateCodes => Symbols.Count != Symbols.Keys.Distinct().Count();
